#include<stdio.h>

int main()
{
    int a = 5;
    float b = 6.5;
    char c = 'A';
    printf("The value of a = %d\n ", a);
    printf("The value of b = %f\n", b);
    printf("The value of c = %c\n", c);
    printf("sum of a and b = %f\n", a + b);
    printf("difference of a and b = %f\n", a - b);
    return 0;
}
